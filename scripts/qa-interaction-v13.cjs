const {chromium}=require('playwright')
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:chromium.executablePath()})
 try{
 const page=await browser.newPage({viewport:{width:393,height:852}}),requests=[],errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/api/generate',async route=>{requests.push(route.request().postDataJSON());await route.fulfill({json:{lines:['先喝几口温水，按自己的口渴程度补充。'],sources:[],generated:true,basis:'general',reason:'AI 通用建议'}})})
 await page.goto('http://127.0.0.1:5173')
 await page.getByRole('dialog',{name:'欢迎来到养令'}).waitFor()
 await page.getByRole('button',{name:'跳过',exact:true}).click()
 await page.getByRole('dialog',{name:'欢迎来到养令'}).waitFor({state:'detached'})
 await page.getByRole('button',{name:/一杯 喝/}).click()
 await page.getByText('AI 通用建议 · 未引用知识库',{exact:true}).waitFor()
 if(requests.length!==1||requests[0].kind!=='cup')throw new Error('Card did not request generation')
 await page.getByRole('button',{name:'换个建议'}).click()
 await page.waitForFunction(()=>document.querySelector('.ylm-sheet-copy')?.textContent.includes('温水'))
 if(requests.length!==2)throw new Error('Retry did not generate')
 await page.getByRole('button',{name:'关闭',exact:true}).click()
 await page.getByRole('button',{name:'问答知识库',exact:true}).click()
 await page.getByRole('textbox',{name:'输入你想问的问题'}).fill('今天想喝水')
 await page.getByRole('button',{name:'发送问题'}).click()
 await page.getByRole('heading',{name:'AI 通用建议',exact:true}).waitFor()
 await page.getByRole('button',{name:'听回答',exact:true}).waitFor()
 await page.reload();await page.getByRole('dialog',{name:'欢迎来到养令'}).waitFor({state:'detached',timeout:4000})
 await page.getByRole('button',{name:'动作识别',exact:true}).click()
 await page.getByRole('button',{name:'语音指导已开启'}).click()
 await page.getByRole('button',{name:'语音指导已关闭'}).waitFor()
 await page.screenshot({path:'.tmp-v13-motion.png'})
 if(errors.length)throw new Error(errors.join('\n'))
 console.log('PASS: skippable/auto-dismiss cover, card/retry requests, uncited label, reading control, voice toggle')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
